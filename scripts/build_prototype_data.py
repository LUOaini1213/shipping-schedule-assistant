"""Generate prototype/data.js from the sample data and the real engine output,
so the clickable prototype never shows an answer the engine did not produce.

    python scripts/build_prototype_data.py           write
    python scripts/build_prototype_data.py --check   fail if the file is stale
"""
import json
import sys
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from ssa import data, engine  # noqa: E402

EXAMPLES = [
    "Which sailings go from Singapore to Rotterdam next week, and what documents do I need to book?",
    "What is the fastest sailing from Shanghai to Singapore?",
    "When is the documentation cut-off for the next sailing from Singapore to Jebel Ali?",
    "How many sailings are there from Singapore to Port Klang in December?",
    "What is the transit time from Singapore to Hamburg?",
    "What happens if I miss the CY cut-off?",
    "What is the freight rate from Singapore to Rotterdam?",
    "Sailings from Singapore to Busan next week?",
    "When is the next sailing to Hamburg?",
    "Sailings from Singapore to Santos next week",
]


def build():
    as_of = date.fromisoformat(data.meta()["as_of"])
    monday = as_of - timedelta(days=as_of.weekday())
    iso = date.isoformat
    windows = [
        {"label": "Any date", "from": iso(as_of), "to": "9999-12-31"},
        {"label": "This week", "from": iso(monday), "to": iso(monday + timedelta(days=6))},
        {"label": "Next week", "from": iso(monday + timedelta(days=7)), "to": iso(monday + timedelta(days=13))},
        {"label": "Next 14 days", "from": iso(as_of), "to": iso(as_of + timedelta(days=14))},
    ]
    examples = []
    for q in EXAMPLES:
        res = engine.answer(q)
        examples.append({"q": q, "refused": res["refused"], "notice": res["notice"], "parts": [
            {"op": p["op"], "reason": p.get("reason"), "text": p["text"], "ids": p["ids"],
             "query": p["query"]} for p in res["parts"]]})
    payload = {
        "meta": data.meta(),
        "ports": [{"code": p["code"], "name": p["name"]} for p in data.ports()],
        "windows": windows,
        "rows": data.rows(),
        "faq": [{"id": e["id"], "topic": e["topic"], "answer": e["answer"]} for e in data.faq()],
        "examples": examples,
    }
    return ("// GENERATED by scripts/build_prototype_data.py - do not edit.\n"
            "// FICTIONAL SAMPLE DATA - not a real carrier schedule.\n"
            "window.SSA_DATA = " + json.dumps(payload, indent=1) + ";\n")


def main():
    path = ROOT / "prototype" / "data.js"
    text = build()
    if "--check" in sys.argv:
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            sys.exit("prototype/data.js is stale: run scripts/build_prototype_data.py")
        print("prototype/data.js is up to date")
        return
    path.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", path.relative_to(ROOT))


if __name__ == "__main__":
    main()
